window.submitQuizAnswer = function(selectedIdx) {
  if (hasAnsweredCurrent) return;
  hasAnsweredCurrent = true;
  quizAnsweredCount++;

  const qItem = currentQuizList[currentQuestionIndex];
  const isCorrect = selectedIdx === qItem.answer;
  if (isCorrect) quizScore++;

  saveStoredJSON("sahityasetu_quiz_stats", { score: quizScore, total: quizAnsweredCount });

  qItem.options.forEach((_, idx) => {
    const btn = document.getElementById(`quizOpt_${idx}`);
    if (!btn) return;
    btn.disabled = true;
    if (idx === qItem.answer) btn.classList.add("correct");
    else if (idx === selectedIdx) btn.classList.add("wrong");
  });

  const feedbackBox = document.getElementById("quizFeedbackBox");
  feedbackBox.classList.remove("hidden");
  feedbackBox.innerHTML = `
    <p style="font-weight:700; color:${isCorrect ? "var(--emerald)" : "var(--accent)"}; margin-bottom:0.35rem;">
      ${isCorrect ? "✓ सटीक उत्तर!" : `✕ सही उत्तर: ${qItem.options[qItem.answer]}`}
    </p>
    <p style="font-size:0.95rem; color:var(--text-muted);">${qItem.explanation}</p>
  `;
  quizScoreBadge.textContent = `स्कोर: ${quizScore} / ${quizAnsweredCount}`;
};

