function getFilteredCorpus() {
  const q = searchInput.value.toLowerCase().trim();
  return SAHITYA_CORPUS.filter(item => {
    const matchCat =
      currentCategory === "all" ||
      (currentCategory === "bookmarks" ? bookmarkedIds.includes(item.id) : item.category === currentCategory);
    const matchText =
      item.title.toLowerCase().includes(q) ||
      item.essence.toLowerCase().includes(q) ||
      item.tags.some(t => t.toLowerCase().includes(q)) ||
      item.analysis.toLowerCase().includes(q);
    return matchCat && matchText;
  });
}

