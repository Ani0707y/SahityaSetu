let parsedPartsState = [];

function isConsonant(ch) {
  const code = ch.charCodeAt(0);
  return (code >= 0x0915 && code <= 0x0939) || (code >= 0x0958 && code <= 0x095F);
}

function isIndependentVowel(ch) {
  const code = ch.charCodeAt(0);
  return code >= 0x0904 && code <= 0x0914;
}

function isDependentMatra(ch) {
  const code = ch.charCodeAt(0);
  return (code >= 0x093E && code <= 0x094C) || code === 0x0962 || code === 0x0963;
}

function parseWordIntoSyllables(word) {
  const chars = Array.from(word);
  const rawUnits = [];
  let i = 0;

  while (i < chars.length) {
    const ch = chars[i];
    if (isConsonant(ch) || isIndependentVowel(ch)) {
      let text = ch;
      let isHalf = false;
      let hasLongVowel = ["आ", "ई", "ऊ", "ए", "ऐ", "ओ", "औ"].includes(ch);
      let hasShortVowel = ["अ", "इ", "उ", "ऋ"].includes(ch);
      let hasAnusvaraOrVisarga = false;
      i++;

      while (i < chars.length) {
        const next = chars[i];
        if (next === "\u093C") {
          text += next;
          i++;
        } else if (next === "\u094D") {
          text += next;
          isHalf = true;
          i++;
          break;
        } else if (isDependentMatra(next)) {
          text += next;
          if (["\u093E", "\u0940", "\u0942", "\u0947", "\u0948", "\u094B", "\u094C"].includes(next)) {
            hasLongVowel = true;
          } else {
            hasShortVowel = true;
          }
          i++;
        } else if (next === "\u0902" || next === "\u0903") {
          text += next;
          hasAnusvaraOrVisarga = true;
          i++;
        } else if (next === "\u0901") {
          text += next;
          i++;
        } else {
          break;
        }
      }

      rawUnits.push({
        text,
        isHalf,
        hasLongVowel,
        hasShortVowel,
        hasAnusvaraOrVisarga
      });
    } else {
      i++;
    }
  }

  const syllables = [];
  let pendingCluster = "";

  for (let idx = 0; idx < rawUnits.length; idx++) {
    const u = rawUnits[idx];
    if (u.isHalf) {
      pendingCluster += u.text;
      if (syllables.length > 0 && idx + 1 < rawUnits.length) {
        const nextChar = rawUnits[idx + 1].text[0];
        const isLightR = nextChar === "र" || nextChar === "ह" || nextChar === "य";
        if (!isLightR) {
          syllables[syllables.length - 1].weight = 2;
        }
      }
    } else {
      const fullText = pendingCluster + u.text;
      pendingCluster = "";
      let weight = (u.hasLongVowel || u.hasAnusvaraOrVisarga) ? 2 : 1;
      syllables.push({
        text: fullText,
        weight
      });
    }
  }

  if (pendingCluster && syllables.length > 0) {
    syllables[syllables.length - 1].text += pendingCluster;
  }

  return syllables;
}

function parseVerseText(rawText) {
  const parts = rawText
    .split(/[,।॥\n|]+/)
    .map(s => s.trim())
    .filter(Boolean);

  return parts.map(partText => {
    const words = partText.split(/\s+/).filter(Boolean);
    const wordSyllables = words.map(w => parseWordIntoSyllables(w)).filter(arr => arr.length > 0);
    return {
      partText,
      wordSyllables
    };
  });
}

function detectChhandFromParts(parts) {
  if (parts.length === 0) return "कोई पंक्ति प्रविष्ट करें";
  const matraCounts = parts.map(p =>
    p.wordSyllables.flat().reduce((sum, s) => sum + s.weight, 0)
  );
  const varnaCounts = parts.map(p => p.wordSyllables.flat().length);
  const totalMatras = matraCounts.reduce((a, b) => a + b, 0);
  const totalVarnas = varnaCounts.reduce((a, b) => a + b, 0);

  if (matraCounts.length >= 2 && matraCounts[0] === 13 && matraCounts[1] === 11) {
    return "दोहा छंद (13 - 11 मात्रा क्रम, कुल 24 मात्राएँ)";
  }
  if (matraCounts.length >= 2 && matraCounts[0] === 11 && matraCounts[1] === 13) {
    return "सोरठा अथवा रोला छंद (11 - 13 मात्रा क्रम, कुल 24 मात्राएँ)";
  }
  if (matraCounts[0] === 16) {
    return "चौपाई छंद (16 मात्राएँ प्रति चरण)";
  }
  if (totalVarnas === 31 || (varnaCounts.length >= 2 && varnaCounts[0] === 16 && varnaCounts[1] === 15)) {
    return "कवित्त / मनहरण घनाक्षरी (16 + 15 = 31 वर्ण)";
  }
  if (totalVarnas >= 22 && totalVarnas <= 26) {
    return `सवैया छंद (${totalVarnas} वर्ण — वर्णिक छंद)`;
  }
  if (totalMatras === 24) {
    return "24 मात्राएँ (दोहा / रोला छंद की संभावना)";
  }
  if (totalMatras === 28) {
    return "28 मात्राएँ (उल्लाला / हरिगीतिका छंद की संभावना)";
  }
  return `मात्रा क्रम: ${matraCounts.join(" - ")} (कुल ${totalMatras} मात्राएँ, ${totalVarnas} वर्ण)`;
}

function renderMatraLab() {
  const totalMatras = parsedPartsState.reduce(
    (acc, p) => acc + p.wordSyllables.flat().reduce((s, x) => s + x.weight, 0),
    0
  );
  const totalVarnas = parsedPartsState.reduce(
    (acc, p) => acc + p.wordSyllables.flat().length,
    0
  );
  const detected = detectChhandFromParts(parsedPartsState);

  matraSummaryBar.innerHTML = `
    <div class="matra-stat-group">
      <span class="stat-pill">कुल मात्राएँ: <strong>${totalMatras}</strong></span>
      <span class="stat-pill">कुल वर्ण (अक्षर): <strong>${totalVarnas}</strong></span>
      <span class="stat-pill">चरण/यति खंड: <strong>${parsedPartsState.length}</strong></span>
    </div>
    <span class="chhand-detect-badge">✨ ${detected}</span>
  `;

  matraLinesOutput.innerHTML = parsedPartsState.map((part, pIdx) => {
    const partMatras = part.wordSyllables.flat().reduce((s, x) => s + x.weight, 0);
    const partVarnas = part.wordSyllables.flat().length;

    const chipsHtml = part.wordSyllables.map((wArr, wIdx) => {
      const syls = wArr.map((syl, sIdx) => {
        const isGuru = syl.weight === 2;
        return `
          <button type="button" class="syllable-chip ${isGuru ? "guru" : "laghu"}"
            onclick="toggleSyllableWeight(${pIdx}, ${wIdx}, ${sIdx})"
            title="मात्रा बदलने के लिए क्लिक करें (लघु I = 1 ⇄ गुरु S = 2)">
            <span class="syl-symbol">${isGuru ? "S" : "I"}</span>
            <span class="syl-char">${syl.text}</span>
            <span class="syl-val">${syl.weight}</span>
          </button>
        `;
      }).join("");
      return syls;
    }).join(`<span class="word-divider"></span>`);

    return `
      <div class="matra-line-card">
        <div class="matra-line-header">
          <span><strong>चरण / यति खंड ${pIdx + 1}:</strong> “${part.partText}”</span>
          <span><strong>${partMatras} मात्राएँ</strong> • ${partVarnas} वर्ण</span>
        </div>
        <div class="syllable-strip">${chipsHtml}</div>
      </div>
    `;
  }).join("");
}

window.toggleSyllableWeight = function(pIdx, wIdx, sIdx) {
  const target = parsedPartsState[pIdx]?.wordSyllables[wIdx]?.[sIdx];
  if (!target) return;
  target.weight = target.weight === 2 ? 1 : 2;
  renderMatraLab();
};

